create table client_fields (
    id bigint generated by default as identity primary key,
    field_key varchar(40) not null unique,
    title varchar(120) not null,
    field_type varchar(20) not null,
    hint varchar(300),
    default_value varchar(500),
    required boolean not null,
    roles varchar(200),
    contract_key varchar(80),
    system_field boolean not null,
    hidden boolean not null,
    deleted boolean not null,
    options varchar(500)
);

create table client_layouts (
    client_type varchar(16) primary key,
    document text not null
);

create table client_field_values (
    client_id bigint not null,
    field_key varchar(40) not null,
    stored text,
    primary key (client_id, field_key)
);
