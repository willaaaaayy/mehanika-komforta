alter table leads add column client_id bigint;
alter table leads add column converted_at timestamp with time zone;
alter table leads add column converted_by varchar(80);

create table clients (
    id bigint generated by default as identity primary key,
    created_at timestamp with time zone not null,
    type varchar(16) not null,
    name varchar(200) not null,
    phone varchar(40),
    email varchar(120),
    inn varchar(12),
    address varchar(300),
    status varchar(16) not null,
    source_lead_id bigint,
    telegram_id bigint,
    telegram_username varchar(64),
    telegram_first_name varchar(64),
    telegram_last_name varchar(64)
);

create table client_events (
    id bigint generated by default as identity primary key,
    client_id bigint not null,
    lead_id bigint,
    at timestamp with time zone not null,
    actor varchar(80) not null,
    action varchar(32) not null
);
