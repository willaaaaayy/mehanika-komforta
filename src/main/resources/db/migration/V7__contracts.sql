create table client_contracts (
    id bigint generated by default as identity primary key,
    created_at timestamp with time zone not null,
    number varchar(40) not null,
    client_name varchar(300) not null,
    client_inn varchar(12),
    object_address varchar(500),
    amount numeric(14, 2) not null,
    original_name varchar(300) not null,
    confirmed boolean not null
);

create unique index client_contracts_number_key on client_contracts (number);

create table contract_schedule (
    id bigint generated by default as identity primary key,
    contract_id bigint not null references client_contracts (id),
    title varchar(200) not null,
    amount numeric(14, 2) not null,
    due_on date,
    kind varchar(16) not null,
    paid_on date,
    paid_amount numeric(14, 2),
    pay_method varchar(16),
    position integer not null
);
